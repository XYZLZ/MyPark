package main

import (
	"bytes"
	"strings"
	"testing"

	"github.com/XYZLZ/MyPark/apps/server/internal/domain/errcodes"
)

func TestRender_DeterministicSortedConst(t *testing.T) {
	in := []errcodes.Code{"http.not_found", "health.not_ready"}
	got := Render(in)
	out := string(got)

	if !strings.HasPrefix(out, "// Code generated by errcodes/gen. DO NOT EDIT.") {
		t.Fatalf("missing generated header, got:\n%s", out)
	}
	hi, ni := strings.Index(out, `"health.not_ready"`), strings.Index(out, `"http.not_found"`)
	if hi < 0 || ni < 0 || hi > ni {
		t.Fatalf("codes not present or not sorted (health=%d http=%d):\n%s", hi, ni, out)
	}
	if !strings.Contains(out, "export const ERROR_CODES = [") || !strings.Contains(out, "] as const;") {
		t.Fatalf("missing const array declaration:\n%s", out)
	}
	if !strings.Contains(out, "export type ErrorCode = typeof ERROR_CODES[number];") {
		t.Fatalf("missing ErrorCode type:\n%s", out)
	}
	if !bytes.Equal(got, Render([]errcodes.Code{"http.not_found", "health.not_ready"})) {
		t.Fatal("Render is not deterministic")
	}
	if !strings.HasSuffix(out, "\n") || strings.Contains(out, "\r") {
		t.Fatal("output must use LF line endings and end with a trailing newline")
	}
	if in[0] != "http.not_found" {
		t.Fatal("Render must not mutate its input")
	}
}

func TestRender_EmptyAndDuplicates(t *testing.T) {
	out := string(Render([]errcodes.Code{"a.b", "a.b"}))
	if strings.Count(out, `"a.b"`) != 1 {
		t.Fatalf("duplicates must be collapsed:\n%s", out)
	}
	empty := string(Render(nil))
	if !strings.Contains(empty, "export const ERROR_CODES = [] as const;") {
		t.Fatalf("empty input should render an empty array:\n%s", empty)
	}
}
