// Command gen exports the errcodes catalog as a TypeScript module so web and
// mobile clients share the exact set of API error codes with the server.
//
// Usage (via go generate in package errcodes):
//
//	go run ./gen -out ../../../../../packages/contracts/src/error-codes.ts
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"slices"
	"strconv"

	"github.com/XYZLZ/MyPark/apps/server/internal/domain/errcodes"
)

const header = "// Code generated by errcodes/gen. DO NOT EDIT.\n"

// Render returns the TypeScript source for codes. Codes are sorted and
// de-duplicated, so the output is byte-deterministic for a given set. The
// input slice is not modified. Output uses LF line endings and ends with a
// trailing newline.
func Render(codes []errcodes.Code) []byte {
	sorted := slices.Clone(codes)
	slices.Sort(sorted)
	sorted = slices.Compact(sorted)

	var b bytes.Buffer
	b.WriteString(header)
	b.WriteString("// Source: apps/server/internal/domain/errcodes/errcodes.go\n\n")
	if len(sorted) == 0 {
		b.WriteString("export const ERROR_CODES = [] as const;\n")
	} else {
		b.WriteString("export const ERROR_CODES = [\n")
		for _, c := range sorted {
			b.WriteString("  ")
			b.WriteString(strconv.Quote(string(c)))
			b.WriteString(",\n")
		}
		b.WriteString("] as const;\n")
	}
	b.WriteString("\nexport type ErrorCode = typeof ERROR_CODES[number];\n")
	return b.Bytes()
}

func main() {
	out := flag.String("out", "", "path of the TypeScript file to write")
	flag.Parse()
	if *out == "" {
		fmt.Fprintln(os.Stderr, "gen: -out is required")
		os.Exit(2)
	}
	if err := write(*out, Render(errcodes.All())); err != nil {
		fmt.Fprintf(os.Stderr, "gen: %v\n", err)
		os.Exit(1)
	}
}

func write(path string, data []byte) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return fmt.Errorf("create output directory: %w", err)
	}
	if err := os.WriteFile(path, data, 0o644); err != nil {
		return fmt.Errorf("write %s: %w", path, err)
	}
	return nil
}
